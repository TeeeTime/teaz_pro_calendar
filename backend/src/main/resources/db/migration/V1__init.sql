-- Each Teaz user's iCloud account. user_id: Keycloak "sub".
CREATE TABLE calendar_account (
    user_id      varchar PRIMARY KEY,
    apple_id     varchar NOT NULL,
    -- The app-specific password, AES-GCM encrypted with CALENDAR_ENCRYPTION_KEY (PasswordCipher).
    password     varchar NOT NULL,
    -- calendar-home-set, on Apple's host for this account (pXX-caldav.icloud.com).
    home_url     varchar NOT NULL,
    connected_at timestamp with time zone NOT NULL,
    -- Start of the last successful sync, null until the first one.
    synced_at    timestamp with time zone,
    sync_error   varchar,
    -- Apple answered 401: no more syncs until the user enters a new password.
    auth_failed  boolean NOT NULL DEFAULT false,
    -- The day recurring events were last expanded on (their window moves with today).
    expanded_on  date
);

-- The account's calendars that hold events (VEVENT), as listed in its calendar home.
CREATE TABLE calendar (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    varchar NOT NULL REFERENCES calendar_account (user_id) ON DELETE CASCADE,
    url        varchar NOT NULL,
    name       varchar NOT NULL,
    color      varchar,
    -- For sync-collection: only changes since then. Null: fetch everything.
    sync_token varchar,
    UNIQUE (user_id, url)
);

-- One CalDAV resource (.ics) as fetched from Apple: an event, or a recurring
-- event with its changed occurrences. The source for event below.
CREATE TABLE calendar_object (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    calendar_id bigint NOT NULL REFERENCES calendar (id) ON DELETE CASCADE,
    href        varchar NOT NULL,
    etag        varchar,
    uid         varchar,
    ics         text NOT NULL,
    recurring   boolean NOT NULL,
    synced_at   timestamp with time zone NOT NULL,
    UNIQUE (calendar_id, href)
);

-- What the views read: every occurrence of each object; for recurring ones,
-- those within calendar.expand-past/-future around today. All-day events start
-- and end at midnight in calendar.timezone.
CREATE TABLE event (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    object_id   bigint NOT NULL REFERENCES calendar_object (id) ON DELETE CASCADE,
    calendar_id bigint NOT NULL,
    user_id     varchar NOT NULL,
    title       varchar NOT NULL,
    location    varchar,
    all_day     boolean NOT NULL,
    starts_at   timestamp with time zone NOT NULL,
    ends_at     timestamp with time zone NOT NULL
);
CREATE INDEX event_user_start ON event (user_id, starts_at);
CREATE INDEX event_object ON event (object_id);
